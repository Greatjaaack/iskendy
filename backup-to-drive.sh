#!/bin/sh
# Выгрузка бэкапов БД «Искенди» на Яндекс.Диск.
#
# Приложение снимает суточную копию в 03:00 и кладёт её в тот же volume, что и
# боевая база. От порчи данных это защищает, от смерти диска — нет. Поэтому
# раз в сутки, уже после снимка, отправляем накопленное наружу.
#
# Почему Яндекс, а не Google. Сначала выгружали на Google Диск, и он подвёл
# дважды подряд: 24 и 25 августа копии не уехали вовсе. Причина не в нас —
# rclone ходит туда под встроенным client_id, общим для всех его пользователей
# в мире, и тот упирается в поминутную квоту. Шесть попыток за четыре часа не
# помогли; ручной запуск через полчаса проходил с первого раза, то есть ждать
# бесполезно, отпускает случайно. Свой client_id завести не вышло: Google
# требует для этого политику конфиденциальности и подтверждённый домен.
#
# У Яндекса для rclone отдельный client_id, и такой квоты там нет: 32 файла
# залились с первого раза за пару секунд. Google убран совсем, а не оставлен
# запасным — держать канал, который отваливается через раз, значит регулярно
# разбирать, где копия есть, а где нет.
#
# Архив на Google Диске («Искенди — бэкапы БД») не тронут и остаётся как есть.
# Всё, что там было, перенесено на Яндекс, включая две самые старые копии,
# которые с сервера уже ушли по ротации.
#
# `copy`, а не `sync`: локально хранятся последние 30 копий, sync стирал бы в
# облаке всё, что старше, — то есть ровно тот архив, ради которого всё затевалось.
set -u

# Ничего не берём из окружения: крон запускает скрипт почти с пустым env, и
# rclone, ищущий конфиг по $HOME, там его не находит — проверено.
PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
export PATH
CONF=/root/.config/rclone/rclone.conf
SRC=/var/lib/docker/volumes/iskendy_app-data/_data/backups
DEST="yadisk:Искенди/бэкапы-сайт"
LOG=/var/log/iskendy-backup-drive.log

echo "=== $(date -Is) выгрузка началась ===" >> "$LOG"

NOMER=1
while [ "$NOMER" -le 3 ]; do
  if rclone --config "$CONF" copy "$SRC" "$DEST" \
       --include "iskendy-*.db.gz" --retries 3 --retries-sleep 20s \
       --low-level-retries 5 --stats-one-line >> "$LOG" 2>&1; then
    echo "$(date -Is) готово с попытки $NOMER" >> "$LOG"
    /root/iskendy/guard.sh --resolve backup_drive "✅ Бэкап базы уехал на Яндекс.Диск." 2>/dev/null
    exit 0
  fi
  echo "$(date -Is) попытка $NOMER не удалась" >> "$LOG"
  NOMER=$((NOMER + 1))
  [ "$NOMER" -le 3 ] && sleep 300
done

echo "$(date -Is) ОШИБКА: не уехало" >> "$LOG"
/root/iskendy/guard.sh --raise backup_drive \
  "🔴 Бэкап базы не уехал на Яндекс.Диск. Копия только на сервере.
$LOG" 2>/dev/null
exit 1
