"""Описание исключения для лога.

У сетевых ошибок httpx текст пустой: `str(ConnectTimeout())` — это "". Строка
`logger.warning("не отправлено: %s", exc)` обрывается на двоеточии и не говорит
ничего. Так двое суток (09–11.09.2026) выглядела лежащая прокси — неотличимо от
испорченного токена, и никто не знал, где искать.

Поэтому в лог всегда идёт имя класса, а текст — только если он есть.
"""


def opisanie(exc: BaseException) -> str:
    """`ConnectTimeout` или `ValueError: неизвестный статус` — без пустых хвостов."""
    text = str(exc)
    return f"{type(exc).__name__}: {text}" if text else type(exc).__name__
